import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const storiesDir = path.resolve("docs/stories");
const outputPath = path.join(storiesDir, "index.md");
const files = (await readdir(storiesDir))
  .filter((file) => file.endsWith(".md") && file !== "index.md")
  .sort((left, right) => left.localeCompare(right, "en"));

function firstHeading(content) {
  return content.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? "Sem título";
}

function frontmatterStatus(content) {
  const frontmatter = content.match(/^---\n([\s\S]*?)\n---(?:\n|$)/)?.[1] ?? "";
  return frontmatter.match(/^status:\s*["']?(.+?)["']?\s*$/m)?.[1]?.trim() ?? null;
}

function explicitStatus(content) {
  const headingStatus = content.match(/(?:^|\n)##\s+Status\s*\n(?:[ \t]*\n)*([^\n#]+)/i)?.[1]?.trim();
  if (headingStatus) return headingStatus;

  const plainStatus = content.match(/^Status:\s*(.+)$/im)?.[1]?.trim();
  if (plainStatus) return plainStatus;

  return content.match(/^\*\*Status:\*\*\s*(.+)$/im)?.[1]?.trim() ?? null;
}

function normalizeStatus(raw) {
  const value = (raw ?? "").replace(/[`*_✅]/g, "").trim();
  const lower = value.toLowerCase();
  if (!value) return "Unknown";
  if (lower.startsWith("done") || lower.includes("complete")) return "Done";
  if (lower.includes("in progress") || lower.includes("inprogress")) return "In Progress";
  if (lower.includes("ready for review")) return "Ready for Review";
  if (lower.startsWith("ready")) return "Ready";
  if (lower.startsWith("draft")) return "Draft";
  if (lower.startsWith("blocked")) return "Blocked";
  return value;
}

function epicFor(file) {
  if (/^1\.1|^custom-/.test(file)) return "Custom";
  if (/adr015/.test(file)) return "ADR-015";
  if (/rec-|rec_/.test(file)) return "Epic 17 (REC-*)";
  const match = file.match(/epic(\d+)/i);
  if (match) return `Epic ${match[1]}`;
  if (/login-redesign/.test(file)) return "Login Redesign";
  return "Project / brownfield";
}

const stories = await Promise.all(
  files.map(async (file) => {
    const content = await readFile(path.join(storiesDir, file), "utf8");
    const rawStatus = frontmatterStatus(content) ?? explicitStatus(content);
    return {
      file,
      title: firstHeading(content),
      status: normalizeStatus(rawStatus),
      epic: epicFor(file),
    };
  })
);

const counts = stories.reduce((result, story) => {
  result[story.status] = (result[story.status] ?? 0) + 1;
  return result;
}, {});
const active = stories.filter((story) => story.status !== "Done");
const generatedAt = new Date().toISOString().slice(0, 10);

const lines = [
  "# Stories Index",
  "",
  `Updated: ${generatedAt}`,
  "Generated by: `npm run docs:stories:index` (all `docs/stories/*.md`, excluding this index)",
  "",
  "## Summary",
  "",
  `- Total stories: ${stories.length}`,
  ...Object.entries(counts)
    .sort(([left], [right]) => left.localeCompare(right, "en"))
    .map(([status, count]) => `- ${status}: ${count}`),
  "",
  "## Active Stories",
  "",
];

if (active.length === 0) {
  lines.push("- None");
} else {
  for (const story of active) {
    lines.push(`- ${story.status}: [${story.title}](./${story.file})`);
  }
}

lines.push("", "## All Stories", "", "| Status | Epic | Story | File |", "|---|---|---|---|");
for (const story of stories) {
  lines.push(`| ${story.status} | ${story.epic} | ${story.title.replaceAll("|", "\\|")} | [${story.file}](./${story.file}) |`);
}

await writeFile(outputPath, `${lines.join("\n")}\n`, "utf8");
console.log(`Generated ${outputPath} with ${stories.length} stories.`);
